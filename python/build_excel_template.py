"""Create excel/KPI_Report_Template.xlsx: Report, Targets, Data (sample month) and How to use.
The Report sheet works with formulas alone; the VBA macro in vba/ReportMacro.bas adds the one-click import and PDF export."""
import sys
import pandas as pd
from openpyxl import Workbook
from openpyxl.formatting.rule import CellIsRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side

extract = sys.argv[1] if len(sys.argv) > 1 else "data/monthly_extract_2017-09.csv"
df = pd.read_csv(extract, parse_dates=["order_date"])

NAVY, GREY = "1F3A5F", "F2F4F7"
thin = Side(style="thin", color="C9D1DB")
wb = Workbook()

# ---------- Report ----------
ws = wb.active
ws.title = "Report"
ws["A1"] = "Monthly KPI Report: Order Fulfilment and Profitability"
ws["A1"].font = Font(bold=True, size=15, color=NAVY)
ws["A2"] = "Each KPI is checked against its target on the Targets sheet. Click 'Generate Report' to load a new month."
ws["A2"].font = Font(italic=True, color="5A6577")
N = 'COUNT(Data!$A$2:$A$20000)'
info = [("Report month", '=TEXT(MIN(Data!$B$2:$B$20000),"mmm yyyy")'),
        ("Order lines", f"={N}"),
        ("KPIs passed", '=COUNTIF($E$8:$E$13,"PASS")&" of 6"')]
for i, (k, f) in enumerate(info):
    ws.cell(row=3 + i, column=1, value=k).font = Font(bold=True)
    ws.cell(row=3 + i, column=2, value=f)
ws["B4"].number_format = "#,##0"

hdr = ["KPI", "Rule", "Target", "Actual", "Status", "What it means"]
for j, h in enumerate(hdr, 1):
    c = ws.cell(row=7, column=j, value=h)
    c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor=NAVY)
    c.alignment = Alignment(horizontal="center")

G, H, I, J, K, L = (f"Data!${c}$2:${c}$20000" for c in "GHIJKL")
actual = [
    f"=SUMPRODUCT(({G}<>\"\")*({G}<={H}))/{N}",
    f"=SUMPRODUCT(({G}<>\"\")*(({G}-{H})<=1))/{N}",
    f"=SUMPRODUCT(({G}<>\"\")*({G}-{H}))/{N}",
    f"=SUM({L})/SUM({K})",
    f"=SUM({J})/SUM({I})",
    f"=COUNTIF({L},\"<0\")/{N}",
]
meaning = ["Delivered within the promised days", "At most 1 day later than promised",
           "Actual minus promised days, on average", "Profit divided by amount paid",
           "Discount given divided by list-price sales", "Share of order lines that lost money"]
fmts = ["0.0%", "0.0%", "0.00", "0.0%", "0.0%", "0.0%"]
for i in range(6):
    r = 8 + i
    ws.cell(row=r, column=1, value=f"=Targets!A{2 + i}")
    ws.cell(row=r, column=2, value=f"=Targets!B{2 + i}")
    c = ws.cell(row=r, column=3, value=f"=Targets!C{2 + i}"); c.number_format = fmts[i]
    c = ws.cell(row=r, column=4, value=actual[i]); c.number_format = fmts[i]
    ws.cell(row=r, column=5, value=f'=IF(B{r}=">=",IF(ROUND(D{r},3)>=C{r},"PASS","FAIL"),IF(ROUND(D{r},3)<=C{r},"PASS","FAIL"))')
    ws.cell(row=r, column=6, value=meaning[i])
    for j in range(1, 7):
        ws.cell(row=r, column=j).border = Border(bottom=thin)
    ws.cell(row=r, column=5).alignment = Alignment(horizontal="center")
ws.conditional_formatting.add("E8:E13", CellIsRule(operator="equal", formula=['"PASS"'], fill=PatternFill("solid", fgColor="D5F0DE"), font=Font(bold=True, color="1A8656")))
ws.conditional_formatting.add("E8:E13", CellIsRule(operator="equal", formula=['"FAIL"'], fill=PatternFill("solid", fgColor="F9E3E0"), font=Font(bold=True, color="C13A2D")))
ws["A15"] = "Generated by the GenerateReport macro (vba/ReportMacro.bas). Data: public DataCo supply-chain dataset."
ws["A15"].font = Font(italic=True, size=9, color="5A6577")
for col, w in zip("ABCDEF", [32, 8, 10, 10, 10, 42]):
    ws.column_dimensions[col].width = w
ws.sheet_view.showGridLines = False
ws.page_setup.orientation = "landscape"
ws.page_setup.fitToWidth = 1

# ---------- Targets ----------
t = wb.create_sheet("Targets")
rows = [("KPI", "Rule", "Target"),
        ("On-time delivery", ">=", 0.45), ("Within 1-day tolerance", ">=", 0.80),
        ("Average slippage (days)", "<=", 0.50), ("Profit margin", ">=", 0.12),
        ("Discount as % of gross sales", "<=", 0.10), ("Loss-making order lines", "<=", 0.15)]
for r in rows:
    t.append(r)
for c in t[1]:
    c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor=NAVY)
for i, f in enumerate(fmts, 2):
    t.cell(row=i, column=3).number_format = f
t.column_dimensions["A"].width = 32
t["E2"] = "Change a target here and the Report updates."

# ---------- Data ----------
d = wb.create_sheet("Data")
d.append(list(df.columns))
for c in d[1]:
    c.font = Font(bold=True); c.fill = PatternFill("solid", fgColor=GREY)
for row in df.itertuples(index=False):
    d.append([row[0], row[1].to_pydatetime()] + list(row[2:]))
for r in range(2, len(df) + 2):
    d.cell(row=r, column=2).number_format = "yyyy-mm-dd hh:mm"
d.freeze_panes = "A2"

# ---------- How to use ----------
h = wb.create_sheet("How to use")
for line in ["1. Export a month from PostgreSQL with sql/06_monthly_extract.sql (change the dates).",
             "2. Save this file as KPI_Report.xlsm and import vba/ReportMacro.bas (Alt+F11 > File > Import File).",
             "3. Add a button on the Report sheet (Developer > Insert > Button) and assign GenerateReport.",
             "4. Click the button, choose the month's CSV. The macro loads it, recalculates and saves",
             "   reports/KPI_Report_YYYY-MM.pdf next to this workbook.",
             "Columns expected in the CSV: " + ", ".join(df.columns)]:
    h.append([line])
h.column_dimensions["A"].width = 110
wb.save("excel/KPI_Report_Template.xlsx")
print("saved, rows:", len(df))
